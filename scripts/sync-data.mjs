#!/usr/bin/env node
/**
 * Copies the generated catalog and the agent-facing llms files from the source
 * repository into this Worker.
 *
 * The Worker keeps a committed copy of the data so `wrangler deploy` does not
 * depend on a sibling checkout. To refresh it:
 *
 *   npm run data:sync
 *   CATALOG_SOURCE=/path/to/Administracion-fuentes-publicas npm run data:sync
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const source = resolve(process.env.CATALOG_SOURCE ?? resolve(root, '../Administracion-fuentes-publicas'));
const outDir = resolve(root, 'src/data');

if (!existsSync(resolve(source, 'catalog.json'))) {
	console.error(`catalog.json not found in ${source}`);
	console.error('Set CATALOG_SOURCE to the checkout of BquantFinance/Administracion-fuentes-publicas.');
	process.exit(1);
}

mkdirSync(outDir, { recursive: true });

const catalog = JSON.parse(readFileSync(resolve(source, 'catalog.json'), 'utf8'));
if (catalog.name !== 'Administración fuentes públicas' || !Array.isArray(catalog.sources)) {
	console.error('The file does not look like the fuentes públicas catalog.');
	process.exit(1);
}

writeFileSync(resolve(outDir, 'catalog.json'), `${JSON.stringify(catalog, null, '\t')}\n`);

const readText = (name) => {
	const path = resolve(source, name);
	return existsSync(path) ? readFileSync(path, 'utf8') : '';
};

const llmsMin = readText('llms-min.txt');
const llms = readText('llms.txt');

// Text modules are generated as TypeScript strings: Wrangler bundles them
// without extra module rules and they stay readable in the repository.
const header = [
	'// Generated by scripts/sync-data.mjs. Do not edit by hand.',
	`// Catalog generated: ${catalog.generated}. Source: ${catalog.repo}`,
	'',
].join('\n');

writeFileSync(
	resolve(outDir, 'llms.ts'),
	`${header}export const llmsMin = ${JSON.stringify(llmsMin)};\n\nexport const llms = ${JSON.stringify(llms)};\n`,
);

console.log(
	`Synced ${catalog.sources.length} sources, ${catalog.indices?.productos?.length ?? 0} products and ` +
		`${catalog.indices?.recetas?.length ?? 0} recipes from ${source}`,
);
